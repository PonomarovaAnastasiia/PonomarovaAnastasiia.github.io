const certificateSlider = document.querySelector("[data-cert-slider]");

const certificateTrack = document.querySelector("[data-cert-track]");

const certificates = [...document.querySelectorAll("[data-cert]")];

const certificatePrev = document.querySelector("[data-cert-prev]");

const certificateNext = document.querySelector("[data-cert-next]");

const certificateCurrent = document.querySelector("[data-cert-current]");

const certificateTotal = document.querySelector("[data-cert-total]");

const certificateViewer = document.querySelector("[data-cert-viewer]");

const certificateViewerImage = document.querySelector(
  "[data-cert-viewer-image]",
);

const certificateCloseButtons = document.querySelectorAll("[data-cert-close]");

let certificateIndex = 0;

let certificatePointerStartX = null;
let certificatePointerEndX = null;

/* =========================================================
   HELPERS
========================================================= */

function normalizeCertificateIndex(index) {
  const total = certificates.length;

  if (!total) return 0;

  if (index < 0) {
    return total - 1;
  }

  if (index >= total) {
    return 0;
  }

  return index;
}

function setCertificateClasses() {
  certificates.forEach((certificate, index) => {
    certificate.classList.remove(
      "is-active",
      "is-prev",
      "is-next",
      "is-prev-2",
      "is-next-2",
    );

    if (index === certificateIndex) {
      certificate.classList.add("is-active");
    }

    if (index === certificateIndex - 1) {
      certificate.classList.add("is-prev");
    }

    if (index === certificateIndex + 1) {
      certificate.classList.add("is-next");
    }

    if (index === certificateIndex - 2) {
      certificate.classList.add("is-prev-2");
    }

    if (index === certificateIndex + 2) {
      certificate.classList.add("is-next-2");
    }
  });
}

/* =========================================================
   CENTER ACTIVE
========================================================= */

function centerActiveCertificate() {
  if (!certificateSlider || !certificateTrack || !certificates.length) {
    return;
  }

  const activeCertificate = certificates[certificateIndex];

  if (!activeCertificate) return;

  const sliderWidth = certificateSlider.getBoundingClientRect().width;

  const activeCenter =
    activeCertificate.offsetLeft + activeCertificate.offsetWidth / 2;

  const target = activeCenter - sliderWidth / 2;

  certificateTrack.style.transform = `translate3d(${-target}px, 0, 0)`;
}

/* =========================================================
   COUNTER
========================================================= */

function updateCertificateCounter() {
  if (certificateCurrent) {
    certificateCurrent.textContent = String(certificateIndex + 1).padStart(
      2,
      "0",
    );
  }

  if (certificateTotal) {
    certificateTotal.textContent = String(certificates.length).padStart(2, "0");
  }
}

/* =========================================================
   UPDATE
========================================================= */

function updateCertificateSlider() {
  if (!certificates.length) return;

  certificateIndex = normalizeCertificateIndex(certificateIndex);

  setCertificateClasses();

  centerActiveCertificate();

  updateCertificateCounter();
}

/* =========================================================
   NEXT / PREV
========================================================= */

function nextCertificate() {
  certificateIndex = normalizeCertificateIndex(certificateIndex + 1);

  updateCertificateSlider();
}

function prevCertificate() {
  certificateIndex = normalizeCertificateIndex(certificateIndex - 1);

  updateCertificateSlider();
}

certificateNext?.addEventListener("click", nextCertificate);

certificatePrev?.addEventListener("click", prevCertificate);

/* =========================================================
   CLICK ON CERTIFICATE
========================================================= */

certificates.forEach((certificate, index) => {
  certificate.addEventListener("click", () => {
    /*
     * Side certificate:
     * make it active first.
     */

    if (index !== certificateIndex) {
      certificateIndex = index;

      updateCertificateSlider();

      return;
    }

    /*
     * Active certificate:
     * open viewer.
     */

    openCertificateViewer(certificate.dataset.image);
  });
});

/* =========================================================
   SWIPE / POINTER
========================================================= */

certificateTrack?.addEventListener("pointerdown", (event) => {
  certificatePointerStartX = event.clientX;

  certificatePointerEndX = event.clientX;

  certificateTrack.setPointerCapture?.(event.pointerId);
});

certificateTrack?.addEventListener("pointermove", (event) => {
  if (certificatePointerStartX === null) {
    return;
  }

  certificatePointerEndX = event.clientX;
});

certificateTrack?.addEventListener("pointerup", (event) => {
  if (certificatePointerStartX === null || certificatePointerEndX === null) {
    return;
  }

  const distance = certificatePointerEndX - certificatePointerStartX;

  const threshold = 45;

  if (Math.abs(distance) >= threshold) {
    if (distance < 0) {
      nextCertificate();
    } else {
      prevCertificate();
    }
  }

  certificatePointerStartX = null;
  certificatePointerEndX = null;

  certificateTrack.releasePointerCapture?.(event.pointerId);
});

certificateTrack?.addEventListener("pointercancel", () => {
  certificatePointerStartX = null;
  certificatePointerEndX = null;
});

/* =========================================================
   CERTIFICATE VIEWER
========================================================= */

function openCertificateViewer(src) {
  if (!certificateViewer || !certificateViewerImage || !src) {
    return;
  }

  certificateViewerImage.src = src;

  certificateViewer.classList.add("is-open");

  certificateViewer.setAttribute("aria-hidden", "false");

  document.body.style.overflow = "hidden";
}

function closeCertificateViewer() {
  if (!certificateViewer) return;

  certificateViewer.classList.remove("is-open");

  certificateViewer.setAttribute("aria-hidden", "true");

  document.body.style.overflow = "";

  if (certificateViewerImage) {
    setTimeout(() => {
      if (!certificateViewer.classList.contains("is-open")) {
        certificateViewerImage.src = "";
      }
    }, 400);
  }
}

certificateCloseButtons.forEach((button) => {
  button.addEventListener("click", closeCertificateViewer);
});

/* =========================================================
   KEYBOARD
========================================================= */

document.addEventListener("keydown", (event) => {
  /*
   * close viewer
   */

  if (
    event.key === "Escape" &&
    certificateViewer?.classList.contains("is-open")
  ) {
    closeCertificateViewer();

    return;
  }

  /*
   * carousel arrows only
   * if certificate section is visible
   */

  if (!certificateSlider) return;

  const rect = certificateSlider.getBoundingClientRect();

  const isVisible = rect.top < window.innerHeight && rect.bottom > 0;

  if (!isVisible) return;

  if (event.key === "ArrowRight") {
    nextCertificate();
  }

  if (event.key === "ArrowLeft") {
    prevCertificate();
  }
});

