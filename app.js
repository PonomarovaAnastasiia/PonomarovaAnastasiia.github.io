function refreshCertificatePositionAfterImages() {
  const certificateImages = certificateTrack?.querySelectorAll("img");

  if (!certificateImages) return;

  certificateImages.forEach((image) => {
    if (image.complete) return;

    image.addEventListener("load", updateCertificateSlider, { once: true });
  });
}

/* =========================================================
   INIT
========================================================= */

function initCertificates() {
  if (!certificateSlider || !certificateTrack || !certificates.length) {
    return;
  }

  certificateIndex = 0;

  updateCertificateSlider();

  refreshCertificatePositionAfterImages();

  requestAnimationFrame(() => {
    updateCertificateSlider();
  });
}

initCertificates();

